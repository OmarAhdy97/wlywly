# -*- coding: utf-8 -*-
import os
import docx
from docx import Document
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.oxml import OxmlElement, parse_xml
from docx.oxml.ns import nsdecls, qn
from PIL import Image

def generate_arabic_only_marketing_doc():
    doc = Document()

    # Configure Margins (0.75 in) & Section RTL
    for section in doc.sections:
        section.top_margin = Inches(0.75)
        section.bottom_margin = Inches(0.75)
        section.left_margin = Inches(0.75)
        section.right_margin = Inches(0.75)
        
        # Enable Section Bidi (RTL layout)
        sectPr = section._sectPr
        bidi = OxmlElement('w:bidi')
        bidi.set(qn('w:val'), '1')
        sectPr.append(bidi)

    # XML Helper Functions for Strict Arabic RTL
    def set_p_rtl(p):
        pPr = p._p.get_or_add_pPr()
        bidi = OxmlElement('w:bidi')
        bidi.set(qn('w:val'), '1')
        pPr.append(bidi)

    def set_r_rtl(run, font_name="Segoe UI"):
        rPr = run._r.get_or_add_rPr()
        rtl = OxmlElement('w:rtl')
        rtl.set(qn('w:val'), '1')
        rPr.append(rtl)
        
        # Set Arabic CS Font
        rFonts = OxmlElement('w:rFonts')
        rFonts.set(qn('w:ascii'), font_name)
        rFonts.set(qn('w:hAnsi'), font_name)
        rFonts.set(qn('w:cs'), font_name)
        rPr.append(rFonts)

    def set_table_rtl(tbl):
        tblPr = tbl._tbl.tblPr
        bidiVisual = OxmlElement('w:bidiVisual')
        bidiVisual.set(qn('w:val'), '1')
        tblPr.append(bidiVisual)

    def set_cell_shading(cell, color_hex):
        tcPr = cell._tc.get_or_add_tcPr()
        shd = parse_xml(f'<w:shd {nsdecls("w")} w:fill="{color_hex}"/>')
        tcPr.append(shd)

    def set_cell_margins(cell, top=120, bottom=120, left=160, right=160):
        tcPr = cell._tc.get_or_add_tcPr()
        tcMar = OxmlElement('w:tcMar')
        for m_name, m_val in [('w:top', top), ('w:bottom', bottom), ('w:left', left), ('w:right', right)]:
            m = OxmlElement(m_name)
            m.set(qn('w:w'), str(m_val))
            m.set(qn('w:type'), 'dxa')
            tcMar.append(m)
        tcPr.append(tcMar)

    def set_table_borders(table, color="E2E8F0"):
        tblPr = table._tbl.tblPr
        borders = parse_xml(
            f'<w:tblBorders {nsdecls("w")}>'
            f'<w:top w:val="single" w:sz="4" w:space="0" w:color="{color}"/>'
            f'<w:bottom w:val="single" w:sz="4" w:space="0" w:color="{color}"/>'
            f'<w:insideH w:val="single" w:sz="4" w:space="0" w:color="{color}"/>'
            f'<w:insideV w:val="single" w:sz="4" w:space="0" w:color="{color}"/>'
            f'<w:left w:val="none"/>'
            f'<w:right w:val="none"/>'
            f'</w:tblBorders>'
        )
        tblPr.append(borders)

    # Formatting Builders
    def add_screen_title(num_arabic, title_arabic):
        p = doc.add_paragraph()
        p.paragraph_format.space_before = Pt(18)
        p.paragraph_format.space_after = Pt(6)
        p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        set_p_rtl(p)
        
        # Number Badge
        r_num = p.add_run(f" الشاشة رقم {num_arabic} : ")
        set_r_rtl(r_num, "Segoe UI")
        r_num.font.size = Pt(13)
        r_num.font.bold = True
        r_num.font.color.rgb = RGBColor(180, 83, 9) # Amber Gold

        r_title = p.add_run(title_arabic)
        set_r_rtl(r_title, "Traditional Arabic")
        r_title.font.size = Pt(18)
        r_title.font.bold = True
        r_title.font.color.rgb = RGBColor(112, 26, 36) # Burgundy

    def add_benefit_box(text):
        tbl = doc.add_table(rows=1, cols=1)
        tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
        set_table_rtl(tbl)
        cell = tbl.rows[0].cells[0]
        cell.width = Inches(6.8)
        set_cell_shading(cell, "FEF3C7") # Warm Amber Shading
        set_cell_margins(cell, top=140, bottom=140, left=180, right=180)

        tcPr = cell._tc.get_or_add_tcPr()
        borders = parse_xml(
            f'<w:tcBorders {nsdecls("w")}>'
            f'<w:right w:val="single" w:sz="24" w:space="0" w:color="D97706"/>'
            f'<w:top w:val="none"/>'
            f'<w:bottom w:val="none"/>'
            f'<w:left w:val="none"/>'
            f'</w:tcBorders>'
        )
        tcPr.append(borders)

        p = cell.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        p.paragraph_format.line_spacing = 1.2
        set_p_rtl(p)
        
        r_head = p.add_run("💡 الفائدة والقيمة التشغيلية للمكتب:\n")
        set_r_rtl(r_head, "Segoe UI")
        r_head.font.size = Pt(11)
        r_head.font.bold = True
        r_head.font.color.rgb = RGBColor(180, 83, 9)

        r_body = p.add_run(text)
        set_r_rtl(r_body, "Segoe UI")
        r_body.font.size = Pt(10.5)
        r_body.font.color.rgb = RGBColor(69, 26, 3)

        doc.add_paragraph().paragraph_format.space_after = Pt(2)

    def add_features_list(features):
        p_head = doc.add_paragraph()
        p_head.paragraph_format.space_before = Pt(6)
        p_head.paragraph_format.space_after = Pt(3)
        p_head.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        set_p_rtl(p_head)
        
        r_head = p_head.add_run("⚡ أبرز الخصائص والمزايا الوظيفية:")
        set_r_rtl(r_head, "Segoe UI")
        r_head.font.size = Pt(11.5)
        r_head.font.bold = True
        r_head.font.color.rgb = RGBColor(15, 23, 42)

        for bold_prefix, text in features:
            p = doc.add_paragraph()
            p.paragraph_format.space_before = Pt(2)
            p.paragraph_format.space_after = Pt(2)
            p.paragraph_format.line_spacing = 1.18
            p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
            set_p_rtl(p)

            r_dot = p.add_run("  ✔ ")
            set_r_rtl(r_dot, "Segoe UI")
            r_dot.font.size = Pt(10.5)
            r_dot.font.bold = True
            r_dot.font.color.rgb = RGBColor(4, 120, 87) # Forest Green

            r_pre = p.add_run(bold_prefix + " : ")
            set_r_rtl(r_pre, "Segoe UI")
            r_pre.font.size = Pt(10.5)
            r_pre.font.bold = True
            r_pre.font.color.rgb = RGBColor(15, 23, 42)

            r_txt = p.add_run(text)
            set_r_rtl(r_txt, "Segoe UI")
            r_txt.font.size = Pt(10)
            r_txt.font.color.rgb = RGBColor(51, 65, 85)

        p_space = doc.add_paragraph()
        p_space.paragraph_format.space_after = Pt(14)

    def add_screenshot_img(img_path):
        if not os.path.exists(img_path):
            return
        
        try:
            with Image.open(img_path) as im:
                w, h = im.size
                is_vertical = (h > w * 1.2) or (w < 800 and h > w)
        except:
            is_vertical = False

        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_before = Pt(6)
        p.paragraph_format.space_after = Pt(8)
        run = p.add_run()
        
        if is_vertical:
            run.add_picture(img_path, width=Inches(3.2))
        else:
            run.add_picture(img_path, width=Inches(6.2))

    # =============================================================
    # COVER / HEADER (100% Arabic)
    # =============================================================
    if os.path.exists("public/logo.png"):
        p_logo = doc.add_paragraph()
        p_logo.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p_logo.add_run().add_picture("public/logo.png", width=Inches(1.6))
        p_logo.paragraph_format.space_after = Pt(8)

    p_main = doc.add_paragraph()
    p_main.alignment = WD_ALIGN_PARAGRAPH.CENTER
    set_p_rtl(p_main)
    r_main = p_main.add_run("أجندة دمياط القضائية — الدليل التسويقي والتشغيلي الشامل")
    set_r_rtl(r_main, "Traditional Arabic")
    r_main.font.size = Pt(24)
    r_main.font.bold = True
    r_main.font.color.rgb = RGBColor(112, 26, 36)

    p_sub = doc.add_paragraph()
    p_sub.alignment = WD_ALIGN_PARAGRAPH.CENTER
    set_p_rtl(p_sub)
    r_sub = p_sub.add_run("استعراض بصري تفصيلي لكافة شاشات المنظومة مع بيان الفوائد التشغيلية والمزايا الوظيفية لكل شاشة")
    set_r_rtl(r_sub, "Segoe UI")
    r_sub.font.size = Pt(12)
    r_sub.font.color.rgb = RGBColor(100, 116, 139)

    doc.add_paragraph().paragraph_format.space_after = Pt(8)

